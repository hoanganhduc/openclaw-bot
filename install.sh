OPENCLAW_VERSION="$(/usr/bin/python3 -I -S -B - "$SCRIPT_DIR/REBUILD-MANIFEST.json" <<'PY'
import json, sys
with open(sys.argv[1], encoding="utf-8") as f:
    print(json.load(f).get("openclaw", {}).get("observed_version", ""))
PY
)"

run() {
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf '[dry-run] %q' "$1"
    shift
    for arg in "$@"; do printf ' %q' "$arg"; done
    printf '\n'
  else
    "$@"
  fi
}

render_copy() {
  local src="$1"
  local dest="$2"
  local ownership="${3:-managed}"
  [[ -e "$src" ]] || return 0
  if [[ "$DRY_RUN" -eq 1 ]]; then
    echo "[dry-run] render-copy $src -> $dest"
    return 0
  fi
  /usr/bin/python3 -I -S -B - "$src" "$dest" "$PREFIX" "$WORKSPACE" "$FORCE_OVERWRITE" "$CONVERGENT" "$ownership" <<'PY'
import os, shutil, stat, sys, tempfile
from pathlib import Path

src, dest, prefix, workspace = map(Path, sys.argv[1:5])
force = sys.argv[5] == "1"
convergent = sys.argv[6] == "1"
ownership = sys.argv[7]
home = Path.home()
OWNER_ROOT_FILES = {
    "AGENTS.md", "HEARTBEAT.md", "IDENTITY.md", "MEMORY.md", "SOUL.md",
    "TOOLS.md", "USER.md", "instruction.md",
}

def render_text(text):
    return (text
        .replace("{{ OPENCLAW_HOME }}", str(prefix))
        .replace("{{ OPENCLAW_WORKSPACE }}", str(workspace))
        .replace("{{ USER_HOME }}", str(home))
        .replace("{{ WRITING_STYLE_FILE }}", str(workspace / "data" / "writing-style.md"))
        .replace("{{ PRIVATE_DATA_DIR }}", str(workspace / "data")))

def is_text(path):
    try:
        read_nofollow(path)[0].decode("utf-8")
        return True
    except Exception:
        return False

def lexists(path):
    return os.path.lexists(path)

def open_directory_create(path):
    path = Path(os.path.abspath(path))
    flags = os.O_RDONLY | os.O_DIRECTORY | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(path.anchor or os.sep, flags)
    try:
        for component in path.parts[1:]:
            try:
                os.mkdir(component, 0o700, dir_fd=descriptor)
            except FileExistsError:
                pass
            next_descriptor = os.open(component, flags, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = next_descriptor
        return descriptor
    except Exception:
        os.close(descriptor)
        raise

def read_nofollow(path):
    parent = open_directory_create(path.parent)
    descriptor = None
    try:
        path_info = os.stat(path.name, dir_fd=parent, follow_symlinks=False)
        descriptor = os.open(
            path.name,
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=parent,
        )
        information = os.fstat(descriptor)
        if (
            not stat.S_ISREG(information.st_mode)
            or information.st_nlink != 1
            or (path_info.st_dev, path_info.st_ino) != (information.st_dev, information.st_ino)
        ):
            raise SystemExit(f"refusing unsafe managed file: {path}")
        chunks = []
        while chunk := os.read(descriptor, 1024 * 1024):
            chunks.append(chunk)
        return b"".join(chunks), stat.S_IMODE(information.st_mode)
    finally:
        if descriptor is not None:
            os.close(descriptor)
        os.close(parent)

def backup_path(path):
    base = path.with_name(path.name + ".bak")
    candidate = base
    idx = 1
    while lexists(candidate):
        information = candidate.lstat()
        if not stat.S_ISREG(information.st_mode) or stat.S_ISLNK(information.st_mode):
            raise SystemExit(f"refusing unsafe backup path: {candidate}")
        candidate = path.with_name(f"{path.name}.bak.{idx}")
        idx += 1
    return candidate

def atomic_write(path, data, mode):
    parent = open_directory_create(path.parent)
    temporary = f".{path.name}.{os.getpid()}.{os.urandom(8).hex()}"
    descriptor = os.open(
        temporary,
        os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
        mode,
        dir_fd=parent,
    )
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode, dir_fd=parent, follow_symlinks=False)
        os.replace(temporary, path.name, src_dir_fd=parent, dst_dir_fd=parent)
        os.fsync(parent)
    finally:
        try:
            os.unlink(temporary, dir_fd=parent)
        except FileNotFoundError:
            pass
        os.close(parent)

def preserve_owner_root(path):
    return ownership == "preserve-root" and path.parent == dest and path.name in OWNER_ROOT_FILES

def write_text_preserving(path, text, mode):
    encoded = text.encode("utf-8")
    if lexists(path):
        try:
            current_bytes, current_mode = read_nofollow(path)
            current = current_bytes.decode("utf-8")
        except Exception:
            current = None
        if current == text:
            atomic_write(path, current_bytes, mode)
            return
        if preserve_owner_root(path) and not force:
            print(f"preserved owner-managed {path}")
            return
        if not (force or convergent):
            raise SystemExit(f"existing managed file differs; rerun with --convergent after review: {path}")
        atomic_write(backup_path(path), current_bytes, current_mode)
    atomic_write(path, encoded, mode)

def copy_preserving(src_path, path, mode):
    source_bytes, _source_mode = read_nofollow(src_path)
    if lexists(path):
        current_bytes, current_mode = read_nofollow(path)
        if source_bytes == current_bytes:
            atomic_write(path, current_bytes, mode)
            return
        if preserve_owner_root(path) and not force:
            print(f"preserved owner-managed {path}")
            return
        if not (force or convergent):
            raise SystemExit(f"existing managed file differs; rerun with --convergent after review: {path}")
        atomic_write(backup_path(path), current_bytes, current_mode)
    atomic_write(path, source_bytes, mode)

source_information = src.lstat()
if stat.S_ISLNK(source_information.st_mode):
    raise SystemExit(f"refusing symlinked install source: {src}")
if stat.S_ISDIR(source_information.st_mode):
    for root, dirs, files in os.walk(src):
        rootp = Path(root)
        dirs[:] = [d for d in dirs if not (rootp / d).is_symlink()]
        for name in files:
            p = rootp / name
            if p.is_symlink():
                raise SystemExit(f"refusing to install symlinked source file: {p}")
            rel = p.relative_to(src)
            out = dest / rel
            # Git records executable intent, not group/world write bits. A
            # cooperative checkout umask may therefore materialize 0775/0664;
            # never carry those write permissions into runnable managed files.
            source_payload, source_mode = read_nofollow(p)
            mode = source_mode & ~0o022
            if is_text(p):
                write_text_preserving(out, render_text(source_payload.decode("utf-8")), mode)
            else:
                copy_preserving(p, out, mode)
elif stat.S_ISREG(source_information.st_mode):
    source_payload, source_mode = read_nofollow(src)
    mode = source_mode & ~0o022
    if is_text(src):
        write_text_preserving(dest, render_text(source_payload.decode("utf-8")), mode)
    else:
        copy_preserving(src, dest, mode)
else:
    raise SystemExit(f"refusing special install source: {src}")
PY
}

render_config_template() {
  local src="$1"
  local dest="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    if [[ "$FORCE_CONFIG" -eq 1 ]]; then
      echo "[dry-run] render-config $src -> $dest"
    else
      echo "[dry-run] validate and preserve active config $dest"
    fi
    return 0
  fi
  if [[ "$FORCE_CONFIG" -eq 1 ]]; then
    local tmp
    tmp="$(mktemp "$(dirname -- "$dest")/.openclaw-config.XXXXXX")"
    FORCE_OVERWRITE=1 render_copy "$src" "$tmp"
    if grep -q '{{[^}][^}]*}}' "$tmp"; then
      echo "ERROR: rendered $src still contains unresolved placeholders; refusing to activate $dest" >&2
      rm -f "$tmp"
      exit 2
    fi
    if [[ -L "$dest" ]]; then
      echo "ERROR: refusing symlinked active config $dest" >&2
      exit 2
    fi
    if [[ -e "$dest" ]]; then
      [[ -f "$dest" ]] || { echo "ERROR: active config is not a regular file: $dest" >&2; exit 2; }
      cp -p "$dest" "$dest.bak"
    fi
    mv "$tmp" "$dest"
  else
    if [[ -L "$dest" ]]; then
      echo "ERROR: refusing symlinked active config $dest" >&2
      exit 2
    elif [[ -e "$dest" ]]; then
      [[ -f "$dest" ]] || { echo "ERROR: active config is not a regular file: $dest" >&2; exit 2; }
      /usr/bin/python3 -I -S -B -m json.tool "$dest" >/dev/null
      echo "Kept active config $dest"
    else
      render_copy "$src" "$dest"
    fi
  fi
}

current_openclaw_version() {
  command -v openclaw >/dev/null 2>&1 || return 1
  openclaw --version 2>/dev/null | awk '/OpenClaw/ {print $2; exit}'
}

create_safe_symlink() {
  local target="$1"
  local link="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    echo "[dry-run] ln -sfn $target $link"
    return 0
  fi
  mkdir -p "$(dirname "$link")"
  if [[ -L "$link" ]]; then
    ln -sfn "$target" "$link"
  elif [[ -e "$link" ]]; then
    echo "preserved existing non-symlink $link; wanted symlink to $target"
  else
    ln -s "$target" "$link"
  fi
}

