usage() {
  cat <<'EOF'
Usage: ./install.sh [--prefix DIR] [--destination-prefix DIR] [--services-only]
       [--install-reviewed-services INSTALL_REVIEWED_USER_SERVICES] [--dry-run]
       [--skip-config] [--skip-docker] [--skip-services] [--skip-openclaw-install]
       [--convergent] [--force-overwrite] [--force-config]

Installs a sanitized OpenClaw rebuild repo into a prefix. This script expects
the repo to have been generated by sync.sh from REBUILD-MANIFEST.json.
EOF
}

