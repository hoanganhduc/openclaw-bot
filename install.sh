while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix) PREFIX="$2"; shift 2 ;;
    --destination-prefix) DESTINATION_PREFIX="$2"; shift 2 ;;
    --services-only) SERVICES_ONLY=1; shift ;;
    --install-reviewed-services)
      [[ "${2:-}" == "INSTALL_REVIEWED_USER_SERVICES" ]] || {
        echo "service installation requires the exact reviewed-activation token" >&2
        exit 2
      }
      INSTALL_REVIEWED_SERVICES=1; SKIP_SERVICES=0; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --skip-config) SKIP_CONFIG=1; shift ;;
    --skip-docker) SKIP_DOCKER=1; shift ;;
    --skip-services) SKIP_SERVICES=1; shift ;;
    --skip-openclaw-install) SKIP_OPENCLAW_INSTALL=1; shift ;;
    --convergent) CONVERGENT=1; shift ;;
    --force-overwrite) FORCE_OVERWRITE=1; shift ;;
    --force-config) FORCE_CONFIG=1; FORCE_OVERWRITE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
